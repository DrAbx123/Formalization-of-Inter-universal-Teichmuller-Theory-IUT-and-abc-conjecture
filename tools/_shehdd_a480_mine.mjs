import { readFileSync, writeFileSync } from 'node:fs';
const ROOT='D:/lean';
const data=JSON.parse(readFileSync(ROOT+'/coord/repo-route-index-data.json','utf8'));
const rows=data.rows||[]; const uncovered=data.uncovered||[];
const bySource={}, byCat={}, byCitable={};
for(const r of uncovered){ bySource[r.source]=(bySource[r.source]||0)+1; byCat[r.category]=(byCat[r.category]||0)+1; byCitable[r.citable]=(byCitable[r.citable]||0)+1; }
const tagRe=(r,names)=>(r.tags||[]).some(t=>names.some(n=>t.includes(n)));
const map=(r)=>{
  const f=r.file, tags=(r.tags||[]).join(' '), decls=(r.decls||[]);
  const has=(names)=>tagRe(r,names)||names.some(n=>f.includes(n));
  const mk=(pre,cons)=>({pre,cons});
  if(has(['Cor312','AbsTopIII05','StepXI','HullDet','COR312'])) return mk('IUT III Cor 3.12 / StepXI 前置对象','组合 tree Contract/Routes/Comparison（或 HullDet/Volume）写 route/hull consumer');
  if(has(['Kummer','LogShell','AbsTopIII','logShell'])) return mk('IUT II Kummer/log-shell 前置对象','组合 SourceLogShell*/absoluteKummer 已编译资产写 log-shell/Kummer consumer');
  if(has(['Ind1','Ind2','Ind3','Thm311','K1K2','IUTIII','Theorem311'])) return mk('IUT III Thm 3.11 前置（Ind1/2/3、K1K2）','组合 Ind*/K1K2 tree 资产写 quotient/boundary/closure consumer');
  if(has(['Hull','H5','H7','holomorphic'])) return mk('IUT III holomorphic hull / H5-H7 前置','组合 HullDet/Volume/CardHull tree 资产写 hull-average/det consumer');
  if(has(['Theta','Gaussian','OddTheta','initialTheta'])) return mk('initial theta / theta 前缀对象','组合 Theta tree 资产（oddTheta/Gaussian/SignedLabel）写 theta value/chain consumer');
  if(has(['Mzk1','GeomCore','RR','lineBundle','Thm25'])) return mk('[Mzk1] Thm 2.5 / GeometricCore / RR 前置','组合 Mzk1* paper consumer 或 RR tree 资产写 GeomCore/RR consumer');
  if(has(['ABCFrontier','Frey','Tate','qNorm','QPilot','ABC','badPrime'])) return mk('ABC bridge: frontier/Frey/Tate/q-pilot 前置','组合 ABCBridge tree 资产写 frontier/height/q 形式 consumer');
  if(has(['GenEll','EtTh','Source'])) return mk('GenEll/EtTh source realization 前置','组合 GenEll/EtTh consumer 链写 realization consumer');
  if(has(['Section0','order','path'])) return mk('IUT III §0 order/path 前置','组合 §0 order/path 资产写 consumer');
  return mk('unmapped（需人工归档）','人工判定：无对应前置对象则归档，不造 adapted 副本');
};
const scored=uncovered.map(r=>{ const m=map(r); let s=0; if(r.citable==='OLEAN_FRESH') s+=3; if(!(r.tags||[]).includes('unmapped')) s+=2; if(r.category==='route'||r.category==='paper-layer') s+=1; return {r,m,s}; });
scored.sort((a,b)=>b.s-a.s||a.r.file.localeCompare(b.r.file));
const L=[];
L.push('# A480-B: tmp / uncovered 资产挖掘（file:decl → 可对应前置对象 → 消费者建议）');
L.push('');
L.push('来源: coord/repo-route-index-data.json（897 行, uncovered='+uncovered.length+'）。规则: 只列已存在文件（citable=OLEAN_FRESH/NO_RESULTS_LINE/EXIT1/STALE_NO_SOURCE/OLEAN_MISSING），不复制、不 adapted；消费者建议均为“组合已编译 tree 资产”类，禁止簿记/占位。');
L.push('');
L.push('## 1. 统计（一行）');
L.push('');
L.push('- uncovered '+uncovered.length+' 个: source='+JSON.stringify(bySource));
L.push('- category='+JSON.stringify(byCat));
L.push('- citable='+JSON.stringify(byCitable)+'（OLEAN_FRESH 即可直接复用为前置资产的候选）');
L.push('- tags 非 unmapped 的 uncovered: '+uncovered.filter(r=>!(r.tags||[]).includes('unmapped')).length+' 个（语义相关，优先挖）。');
L.push('');
L.push('## 2. 高价值 uncovered（按 citable/语义排序，前 150）');
L.push('');
L.push('| file | decls | citable | 可对应前置对象 | 消费者建议 |');
L.push('|---|---|---|---|---|');
for(const {r,m} of scored.slice(0,150)){
  const decls=(r.decls||[]).slice(0,3).join(', ');
  L.push('| '+r.file+' | '+decls+' | '+r.citable+' | '+m.pre+' | '+m.cons+' |');
}
L.push('');
L.push('## 3. 其余 uncovered（全量压缩清单: file | category | citable | 前置对象）');
L.push('');
for(const {r,m} of scored.slice(150)) L.push('- '+r.file+' | '+r.category+' | '+r.citable+' | '+m.pre);
L.push('');
L.push('## 4. 使用建议');
L.push('');
L.push('1. 对 citable=OLEAN_FRESH 且 tags 非 unmapped 的行，优先核对 decls 与 tree 资产是否重复：重复则只登记为“已有资产消费者”，不新写 Lean。');
L.push('2. 对 tmp/paper 层 EXIT0/OLEAN_FRESH 行，若其 decls 已被其他 consumer 消费，直接标注消费者；若无消费者，写“真实组合 consumer”（引用现有定理，无 sorry/空声明）。');
L.push('3. 对 citable=EXIT1/STALE_NO_SOURCE 行：先复跑/修复原文件（queue 修错），不新建 adapted 副本。');
L.push('4. 对 unmapped 且无前置对象的行：归档登记（DAG-BLOCKED/说明），不批量造文件。');
writeFileSync(ROOT+'/coord/TMP-ASSET-MINE.md', L.join('\n')+'\n');
