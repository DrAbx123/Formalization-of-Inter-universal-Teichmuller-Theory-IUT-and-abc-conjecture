def to_lean(a):
    parts=[]
    for e,c in enumerate(a):
        if c==0: continue
        if e==0: parts.append(f"C {c}")
        elif e==1: parts.append(f"C {c} * X")
        else: parts.append(f"C {c} * X ^ {e}")
    return " + ".join(parts) if parts else "C 0"

